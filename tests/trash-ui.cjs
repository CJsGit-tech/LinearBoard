// Runs exclusively against a temporary database and test-only server.
const { chromium } = require('playwright');
const { spawn } = require('node:child_process');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'linearboard-trash-ui-'));
  const port = process.env.LINEARBOARD_QA_PORT || '8782';
  const base = process.env.LINEARBOARD_TEST_URL || `http://127.0.0.1:${port}`;
  let server, browser;
  const errors = [];
  const request = async (path, body) => {
    const response = await fetch(base + '/api/' + path, { method: body ? 'POST' : 'GET', headers: {'Content-Type':'application/json', 'X-LinearBoard-Actor':'user'}, body: body ? JSON.stringify(body) : undefined });
    const data = await response.json();
    assert.ok(response.ok, JSON.stringify(data));
    return data;
  };
  try {
    if (!process.env.LINEARBOARD_TEST_URL) {
    server = spawn('python3', ['server.py', '--port', port, '--db', path.join(temp, 'test.sqlite')], {cwd:path.resolve(__dirname, '..')});
    await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); server.once('exit', code => reject(Error('server exited '+code))); });
    }
    const team = (await request('state')).teams[0];
    const project = await request('projects', {team_id:team.id, name:'Trash QA'});
    const parent = await request('issues', {project_id:project.id, title:'Parent QA', category:'FrontEnd'});
    const child = await request('issues', {project_id:project.id, title:'Child QA', category:'FrontEnd', parent_id:parent.id});
    browser = await chromium.launch({channel:'chrome', headless:true});
    const page = await browser.newPage({locale:"zh-TW",viewport:{width:1440,height:960}});
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base);
    await page.getByRole('button', {name:'工作區設定', exact:true}).click();
    const settingsNav = page.getByRole('navigation', {name:'設定分類'});
    await settingsNav.getByRole('button', {name:'標籤與群組', exact:true}).click();
    await page.getByRole('heading', {name:'標籤與群組', exact:true}).waitFor();
    await settingsNav.getByRole('button', {name:'整合與說明', exact:true}).click();
    await page.getByRole('link', {name:'操作指南', exact:true}).waitFor();
    await page.setViewportSize({width:390, height:844});
    await settingsNav.getByRole('button', {name:'垃圾桶', exact:true}).click();
    await page.getByRole('region', {name:'垃圾桶'}).getByText('垃圾桶是空的').waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth));
    await page.screenshot({path:'/tmp/linearboard-settings-mobile.png'});
    await page.setViewportSize({width:1440, height:960});
    await page.getByRole('button', {name:'返回專案', exact:true}).click();
    await page.locator('.issue-row[data-id="'+parent.id+'"]').click();
    await page.getByRole('button', {name:'刪除', exact:true}).click();
    await page.getByRole('heading', {name:'移至垃圾桶', exact:true}).waitFor();
    assert.ok((await page.locator('dialog').innerText()).includes('任務 2'));
    await page.getByRole('button', {name:'移至垃圾桶', exact:true}).click();
    await page.locator('dialog').waitFor({state:'hidden'});
    assert.equal((await request('state')).issues.length, 0);
    await page.getByRole('button', {name:'工作區設定', exact:true}).click();
    await page.getByRole('button', {name:'垃圾桶', exact:true}).click();
    const trash = page.getByRole('region', {name:'垃圾桶'});
    await trash.getByText('Parent QA', {exact:true}).waitFor();
    await page.screenshot({path:'/tmp/linearboard-trash-ui.png', fullPage:false});
    await trash.getByRole('button', {name:'還原', exact:true}).click();
    await trash.getByText('垃圾桶是空的').waitFor();
    let state = await request('state');
    assert.equal(state.issues.find(i=>i.id===child.id).parent_id, parent.id);
    await request('attachments', {target_kind:'issues', target_id:parent.id, name:'QA attachment', external_url:'https://example.invalid/qa', approval:'draft'});
    await page.getByRole('button', {name:'返回專案', exact:true}).click();
    await page.locator('.issue-row[data-id="'+parent.id+'"]').click();
    await page.getByRole('textbox', {name:'任務標題'}).fill('Unsaved parent draft');
    await page.getByRole('button', {name:'刪除附件 QA attachment', exact:true}).click();
    await page.getByRole('button', {name:'移至垃圾桶', exact:true}).click();
    await page.getByRole('textbox', {name:'任務標題'}).waitFor();
    assert.equal(await page.getByRole('textbox', {name:'任務標題'}).inputValue(), 'Unsaved parent draft');
    await page.getByRole('button', {name:'關閉任務', exact:true}).click();
    await page.locator('.issue-row[data-id="'+parent.id+'"]').click();
    await page.getByRole('button', {name:'刪除', exact:true}).click();
    await page.getByRole('button', {name:'移至垃圾桶', exact:true}).click();
    await page.locator('dialog').waitFor({state:'hidden'});
    await page.getByRole('button', {name:'工作區設定', exact:true}).click();
    await page.getByRole('button', {name:'垃圾桶', exact:true}).click();
    await trash.getByText('Parent QA', {exact:true}).waitFor();
    await trash.getByRole('button', {name:'清空垃圾桶', exact:true}).click();
    await page.getByRole('heading', {name:'永久刪除', exact:true}).waitFor();
    await page.getByRole('button', {name:'永久刪除', exact:true}).last().click();
    await page.locator('dialog').waitFor({state:'hidden'});
    await trash.getByText('垃圾桶是空的').waitFor();
    assert.equal((await request('trash')).length, 0);
    const parent2 = await request('issues', {project_id:project.id, title:'Batch parent', category:'FrontEnd'});
    const child2 = await request('issues', {project_id:project.id, title:'Batch child', category:'FrontEnd', parent_id:parent2.id});
    const other = await request('issues', {project_id:project.id, title:'Not selected', category:'FrontEnd'});
    await page.getByRole('button', {name:'返回專案', exact:true}).click();
    await page.getByRole('checkbox', {name:'選取 '+parent2.identifier}).check();
    await page.getByRole('checkbox', {name:'選取 '+child2.identifier}).check();
    await page.getByRole('button', {name:'動作', exact:true}).click();
    await page.getByRole('menuitem', {name:'刪除', exact:true}).click();
    await page.getByRole('heading', {name:'移至垃圾桶', exact:true}).waitFor();
    assert.ok((await page.locator('dialog').innerText()).includes('任務 2'));
    await page.getByRole('button', {name:'移至垃圾桶', exact:true}).click();
    await page.locator('dialog').waitFor({state:'hidden'});
    assert.deepEqual((await request('state')).issues.map(issue=>issue.id), [other.id]);
    await page.getByRole('button', {name:'工作區設定', exact:true}).click();
    await page.getByRole('button', {name:'垃圾桶', exact:true}).click();
    await trash.getByText('2 個任務', {exact:true}).waitFor();
    await trash.getByRole('button', {name:'還原', exact:true}).click();
    await trash.getByText('垃圾桶是空的').waitFor();
    state = await request('state');
    assert.equal(state.issues.find(issue=>issue.id===child2.id).parent_id, parent2.id);
    assert.equal(state.issues.length, 3);
    await page.getByRole('button', {name:'返回專案', exact:true}).click();
    await page.getByRole('button', {name:'刪除專案 Trash QA', exact:true}).click();
    await page.getByRole('heading', {name:'移至垃圾桶', exact:true}).waitFor();
    assert.ok((await page.locator('dialog').innerText()).includes('任務 3'));
    await page.getByRole('button', {name:'移至垃圾桶', exact:true}).click();
    await page.locator('dialog').waitFor({state:'hidden'});
    assert.equal((await request('state')).projects.length, 0);
    const projectList = page.getByRole('navigation', {name:'專案清單'});
    assert.equal(await projectList.locator('[data-project-id]').count(), 0);
    await page.getByRole('button', {name:'工作區設定', exact:true}).click();
    await page.getByRole('button', {name:'垃圾桶', exact:true}).click();
    await trash.getByText('Trash QA', {exact:true}).waitFor();
    await trash.getByRole('button', {name:'還原', exact:true}).click();
    await trash.getByText('垃圾桶是空的').waitFor();
    state = await request('state');
    assert.equal(state.projects[0].id, project.id);
    assert.equal(state.issues.length, 3);
    assert.equal(await projectList.locator('[data-project-id="'+project.id+'"]').getAttribute('aria-current'), 'page');
    assert.equal(await page.getByText('封存紀錄', {exact:true}).count(), 0);
    const relation = await request('relations', {source_id:parent2.id, target_id:other.id, relation:'related'});
    await page.getByRole('button', {name:'返回專案', exact:true}).click();
    await page.locator('.issue-row[data-id="'+parent2.id+'"]').click();
    assert.equal(await page.getByRole('button', {name:'封存', exact:true}).count(), 0);
    await page.getByRole('button', {name:'移除關聯', exact:true}).click();
    await page.getByRole('button', {name:'移至垃圾桶', exact:true}).click();
    await page.getByRole('textbox', {name:'任務標題'}).waitFor();
    assert.equal((await request('state')).relations.length, 0);
    await page.getByRole('button', {name:'關閉任務', exact:true}).click();
    await page.getByRole('button', {name:'工作區設定', exact:true}).click();
    await page.getByRole('button', {name:'垃圾桶', exact:true}).click();
    const relationRow = trash.locator('.setting-row').filter({hasText:parent2.identifier});
    await relationRow.getByRole('button', {name:'還原', exact:true}).click();
    assert.equal((await request('state')).relations[0].id, relation.id);
    assert.deepEqual(errors, []);
    console.log('PASS: UI issue, project and relation trash/restore, manual empty, no archive controls, and no browser errors');
  } catch (error) { console.error(error); process.exitCode=1; }
  finally {
    if (browser) await browser.close();
    if (server && server.exitCode===null) { server.kill('SIGTERM'); await new Promise(resolve=>server.once('exit',resolve)); }
    await fs.rm(temp, {recursive:true,force:true});
  }
})();
